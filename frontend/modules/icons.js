// Tier badge_class -> icon name, matching backend/scrapers/analyzer.py compute_liquidity_tier()
const TIER_ICONS = {
  'liquidity-tier-1': 'zap',
  'liquidity-tier-2': 'flame',
  'liquidity-tier-3': 'truck',
  'liquidity-tier-4': 'hourglass',
};

export function liquidityIcon(badgeClass, opts) {
  return icon(TIER_ICONS[badgeClass] || 'zap', opts);
}

export function starRow(rating, opts) {
  const full = Math.round(rating);
  return Array.from({ length: 5 }, (_, i) =>
    icon('star', { ...opts, className: (opts?.className || '') + (i < full ? ' star-filled' : ' star-empty') })
  ).join('');
}
